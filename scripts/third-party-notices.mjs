#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.md from package-lock.json: every production dependency that the
// web app bundles (apps/web and the packages/* it uses), with version and declared licence,
// plus the fixed notices for fonts, elkjs (EPL-2.0), Python/R components and data.
//   node scripts/third-party-notices.mjs          write the file
//   node scripts/third-party-notices.mjs --check  exit 1 if the file is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'THIRD_PARTY_NOTICES.md');
const pk = JSON.parse(readFileSync(join(ROOT, 'package-lock.json'), 'utf8')).packages;

function resolve(base, name) {
  for (;;) {
    const p = `${base ? `${base}/` : ''}node_modules/${name}`;
    if (pk[p]) return p;
    if (!base) return null;
    const i = base.lastIndexOf('/node_modules/');
    base = i < 0 ? '' : base.slice(0, i);
  }
}
const seen = new Map();
function walk(path) {
  const e = pk[path];
  if (!e) return;
  for (const n of Object.keys(e.dependencies ?? {})) {
    const r = resolve(path, n);
    if (!r || seen.has(r)) continue;
    const target = pk[r].link ? pk[r].resolved : r;
    seen.set(r, target);
    walk(target);
  }
}
for (const w of ['apps/web', 'packages/contracts', 'packages/engine', 'packages/method-registry'])
  walk(w);

const PERMISSIVE = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD']);
const rows = [...seen]
  .map(([r, t]) => [r.replace(/.*node_modules\//, ''), pk[t].version, pk[t].license ?? 'UNKNOWN'])
  .filter(([n]) => !n.startsWith('@sem-studio/'))
  .sort((a, b) => a[0].localeCompare(b[0]));

const unexpected = rows.filter(
  ([n, , l]) =>
    !PERMISSIVE.has(l) &&
    !(n.startsWith('@fontsource') && l === 'OFL-1.1') &&
    !(n === 'elkjs' && l === 'EPL-2.0 OR GPL-3.0-or-later') &&
    l !== 'MIT AND ISC AND BSD-3-Clause',
);
if (unexpected.length) {
  console.error('Review these licences before shipping:', unexpected);
  process.exit(1);
}

const text = `# Third-party notices

SEM Studio is released under the MIT License (\`LICENSE\`). It bundles or relies on the
open-source components below, each under its own licence. Generated by
\`scripts/third-party-notices.mjs\` from \`package-lock.json\`; do not edit by hand.

## Bundled in the web app

| Package | Version | Licence |
|---|---|---|
${rows.map(([n, v, l]) => `| ${n} | ${v} | ${l} |`).join('\n')}

### elkjs (Eclipse Layout Kernel)

elkjs is dual-licensed EPL-2.0 OR GPL-3.0-or-later; SEM Studio uses it, unmodified, under the
**Eclipse Public License 2.0** (https://www.eclipse.org/legal/epl-2.0/). Source code:
https://github.com/kieler/elkjs (and the Eclipse Layout Kernel, https://github.com/eclipse/elk).
The EPL-2.0 applies to elkjs only, not to SEM Studio.

### Fonts

Inter (© The Inter Project Authors) and JetBrains Mono (© The JetBrains Mono Project Authors)
are self-hosted through @fontsource-variable under the SIL Open Font License 1.1
(https://openfontlicense.org).

## Python (exported scripts and notebooks)

\`semstudio_bundle.py\` is SEM Studio's own code (MIT). At run time it uses numpy and scipy
(BSD-3-Clause); the notebooks also use pandas (BSD-3-Clause) and matplotlib (matplotlib
licence, PSF-based). Notebook 05 optionally installs semopy (MIT) for a cross-check. None of
these are redistributed by SEM Studio.

## R (exported scripts and the verification oracle)

Exported R scripts and \`services/r-engine\` call cSEM (GPL-3) and lavaan (GPL ≥ 2), which users
install themselves from CRAN. SEM Studio contains no code from these packages and does not
redistribute them; its estimation engines are independent implementations verified against
their output.

## Data

- \`packages/fixtures/third-party/smartpls-samples/acsi-2015/\`: Hult, T. & Morgeson, F. (2023),
  "The American Customer Satisfaction Index (ACSI): A Sample Dataset and Description",
  Mendeley Data, V2, doi:10.17632/64xkbj2ry5.2, licensed under CC BY 4.0
  (https://creativecommons.org/licenses/by/4.0/). Changes: converted to CSV; missing-data codes
  written as empty fields. Not covered by SEM Studio's MIT License.
- All other datasets in the repository are synthetic, generated by
  \`packages/fixtures/scripts/generate_synthetic.py\`, and are part of SEM Studio (MIT).
`;

if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(OUT, 'utf8');
    } catch {
      return '';
    }
  })();
  if (current !== text) {
    console.error(
      'THIRD_PARTY_NOTICES.md is out of date: run node scripts/third-party-notices.mjs',
    );
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES.md is up to date');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${rows.length} packages)`);
}
