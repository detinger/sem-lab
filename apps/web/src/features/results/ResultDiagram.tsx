import type { NormalizedSemResult, SemLayout, SemModel } from '@sem-lab/contracts';
import { useEffect, useMemo, useState } from 'react';
import { sceneToSvg } from '@/features/modeler/export/svg-export';
import { computeAutoLayout } from '@/features/modeler/layout/auto-layout';
import type { OverlayScale } from '@/features/modeler/overlay';
import { buildScene } from '@/features/modeler/scene';
import { useModeler } from '@/features/modeler/store';

/** APA-style significance stars for a path's p-value. */
function stars(p: number | null): string {
  if (p === null) return '';
  if (p < 0.001) return '***';
  if (p < 0.01) return '**';
  if (p < 0.05) return '*';
  return '';
}

/**
 * The estimated structural model as a static diagram: the exact model the run was computed from,
 * with path coefficients (and significance stars) on the paths and R² in each endogenous construct.
 * Reuses the Modeler's scene/overlay/SVG pipeline, so it always matches the canvas.
 */
export function ResultDiagram({
  model,
  result,
  scale,
}: {
  model: SemModel;
  result: NormalizedSemResult;
  scale: OverlayScale;
}) {
  const currentLayout = useModeler((s) => s.layout);
  const [auto, setAuto] = useState<{ model: SemModel; layout: SemLayout } | null>(null);

  // Positions: reuse the Modeler's current layout when it covers this (analysed) model; otherwise
  // lay it out automatically (async) so a historical run still renders.
  const covered = useMemo(
    () => [...model.constructs, ...model.indicators].every((n) => currentLayout.nodes[n.id]),
    [model, currentLayout],
  );
  useEffect(() => {
    if (covered) return;
    let alive = true;
    computeAutoLayout(model, currentLayout.settings)
      .then((r) => {
        if (alive)
          setAuto({ model, layout: { nodes: r.positions, settings: currentLayout.settings } });
      })
      .catch(() => {});
    return () => {
      alive = false;
    };
  }, [covered, model, currentLayout]);

  const layout = covered ? currentLayout : auto?.model === model ? auto.layout : null;

  const svg = useMemo(() => {
    if (!layout || model.constructs.length === 0) return null;
    const scene = buildScene(model, layout, { overlay: { mode: 'estimate', result, scale } });
    // Append significance stars to the structural coefficient pills (β***). The p-value belongs to
    // the inferential estimate regardless of the displayed scale, so take it from any matching path.
    const edges = scene.edges.map((e) => {
      if (e.kind !== 'structural' || !e.pill) return e;
      const rel = model.relationships.find((r) => r.id === e.id);
      const pval =
        result.parameters.find(
          (x) =>
            x.kind === 'path' &&
            x.pValue !== null &&
            (x.relationshipId === e.id ||
              (rel !== undefined && x.sourceId === rel.sourceId && x.targetId === rel.targetId)),
        )?.pValue ?? null;
      const s = stars(pval);
      return s ? { ...e, pill: `${e.pill}${s}` } : e;
    });
    return sceneToSvg({ ...scene, edges }, { background: 'white', title: 'Estimated model' });
  }, [layout, model, result, scale]);

  if (model.constructs.length === 0) return null;
  if (svg === null) return <p className="rs-empty">Preparing the model diagram…</p>;
  return (
    <figure className="rs-diagram">
      {/* Generated by sceneToSvg from our own data; all text is XML-escaped there. */}
      <div className="rs-diagram__canvas" dangerouslySetInnerHTML={{ __html: svg }} />
      <figcaption className="rs-diagram__legend">
        Path coefficients with significance (<strong>*</strong>&nbsp;p&lt;.05, <strong>**</strong>
        &nbsp;p&lt;.01, <strong>***</strong>&nbsp;p&lt;.001) and R² in each endogenous construct.
        Loadings or weights are shown on the measurement arrows.
      </figcaption>
    </figure>
  );
}
