def generate():
    outputs = {}
    table = []
    readme_rows = []
    tam_files = None
    for fn in CASES:
        cid_, files, _ = fn()
        outputs[cid_] = files
        man = json.loads(files["manifest.json"])
        table.append((cid_, man["n"], man["nColumns"], man["sha256"]))
        readme_rows.append((cid_, man["kind"], man["n"], man["purpose"]))
        if cid_ == "tam-mediation":
            tam_files = files
    cid_, files = case_broken_mapping(tam_files)
    outputs[cid_] = files
    table.append((cid_, None, None, None))
    readme_rows.append((cid_, "model-only", None, json.loads(files["manifest.json"])["purpose"]))
    flat = {f"{c}/{name}": b for c, fs in outputs.items() for name, b in fs.items()}
    flat["README.md"] = readme(readme_rows)
    return flat, table


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify files on disk instead of writing")
    ap.add_argument("--out-dir", type=Path, default=OUT_DIR, help="output directory (default: packages/fixtures/synthetic)")
    args = ap.parse_args(argv)
    out_dir = args.out_dir
    try:
        flat, table = generate()
    except GenerationError as exc:
        print(f"GENERATION FAILED: {exc}", file=sys.stderr)
        return 2
    if args.check:
        bad = []
        for rel, b in sorted(flat.items()):
            path = out_dir / rel
            if not path.is_file() or path.read_bytes() != b:
                bad.append(rel)
        on_disk = {str(p.relative_to(out_dir)) for p in out_dir.rglob("*") if p.is_file() and p.name != ".DS_Store"} if out_dir.exists() else set()
        extra = sorted(on_disk - set(flat))
        for rel in bad:
            print(f"DIFFERS: {rel}", file=sys.stderr)
        for rel in extra:
            print(f"UNEXPECTED: {rel}", file=sys.stderr)
        if bad or extra:
            print(f"--check failed ({len(bad)} differing, {len(extra)} unexpected). Regenerate with:\n  {REGEN_CMD}", file=sys.stderr)
            return 1
        print(f"--check OK: {len(flat)} files match")
        return 0
    for rel, b in sorted(flat.items()):
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_bytes() != b:
            path.write_bytes(b)
    print(f"{'case':28} {'rows':>5} {'cols':>5}  sha256(data.csv)")
    for cid_, n, p, h in table:
        print(f"{cid_:28} {n if n is not None else '-':>5} {p if p is not None else '-':>5}  {h or '- (model-only)'}")
    for cid_, (ce, me) in VERIFY.items():
        print(f"exact check {cid_}: max|S-Sigma| = {ce:.3e}, max|mean-mu| = {me:.3e}")
    return 0


