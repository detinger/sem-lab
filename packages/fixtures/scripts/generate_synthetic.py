def finish(case_id, *, title, kind, purpose, seed, header, rows, meta, population, model, analyses, truths,
           extra_manifest=None):
    files = {}
    data = csv_bytes(header, rows)
    h2, parsed = parse_csv(data)
    require(h2 == header, "header round trip")
    for j, name in enumerate(header):
        md = meta[name]
        if md["scaleType"] == "ORDINAL":
            for r in parsed:
                v = r[j]
                require(v is None or (isinstance(v, int) and md["scaleMin"] <= v <= md["scaleMax"]),
                        f"{case_id}:{name}: Likert value {v!r} not an integer in range")
    files["data.csv"] = data
    files["columns.json"] = json_bytes(columns_info(header, parsed, meta))
    if population is not None:
        files["population.json"] = json_bytes(population)
    files["model.json"] = json_bytes(model)
    files["analyses.json"] = json_bytes(analyses)
    man = {"caseId": case_id, "title": title, "kind": kind, "synthetic": True, "purpose": purpose,
           "seed": seed, "n": len(rows), "nColumns": len(header), "sha256": sha(data),
           "generator": GENERATOR, "generatorVersion": GENERATOR_VERSION, "expectedTruths": truths,
           "statement": "SYNTHETIC benchmark/teaching data generated by this repository; represents no real study."}
    man.update(extra_manifest or {})
    files["manifest.json"] = json_bytes(man)
    return case_id, files, parsed


