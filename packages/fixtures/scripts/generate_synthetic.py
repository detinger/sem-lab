def cell(v):
    if v is None:
        return ""
    if isinstance(v, bool):
        raise GenerationError("boolean cell")
    if isinstance(v, int):
        return str(v)
    require(math.isfinite(v), "non-finite cell")
    return repr(float(v))


def csv_bytes(header, rows):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    for r in rows:
        w.writerow([cell(v) for v in r])
    return buf.getvalue().encode("utf-8")


def json_bytes(obj):
    return (json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False, allow_nan=False) + "\n").encode("utf-8")


def parse_csv(data):
    rows = list(csv.reader(io.StringIO(data.decode("utf-8"))))
    header, body = rows[0], rows[1:]
    parsed = [[None if v == "" else (int(v) if v.lstrip("-").isdigit() else float(v)) for v in r] for r in body]
    return header, parsed


def columns_info(header, rows, meta):
    info = []
    for j, name in enumerate(header):
        vals = [r[j] for r in rows if r[j] is not None]
        md = meta[name]
        info.append({"name": name, "scaleType": md["scaleType"], "scaleMin": md.get("scaleMin"),
                     "scaleMax": md.get("scaleMax"), "observedMin": min(vals), "observedMax": max(vals),
                     "nMissing": len(rows) - len(vals), "nUnique": len(set(vals))})
    return info


