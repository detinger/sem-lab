#!/usr/bin/env python3
"""Generate the SYNTHETIC benchmark datasets in packages/fixtures/synthetic/.

Every dataset written here is synthetic benchmark/teaching data generated by this
script from an explicitly stated population model. None of it represents a real study.

Usage (from the repository root; ephemeral environment, numpy only):

    uv run --python 3.12 --with numpy python packages/fixtures/scripts/generate_synthetic.py
    uv run --python 3.12 --with numpy python packages/fixtures/scripts/generate_synthetic.py --check

--check regenerates everything in memory and exits 1 if any file on disk differs, is
missing, or is not produced by this script.

Two kinds of data:

* SAMPLED: rows drawn from N(mu, Sigma) of the population model (x = mu + D chol(R) z),
  optionally discretised to Likert categories (category = base + number of thresholds
  exceeded by the standardised continuous response).
* EXACT: a standard-normal matrix is centred, whitened with the inverse Cholesky factor
  of its own (N-1)-divisor covariance, recoloured with chol(Sigma) and shifted by mu, so
  the sample covariance equals Sigma and the sample means equal mu (to rounding).

Determinism. The only numpy calls that influence written bytes are
numpy.random.Generator(PCG64(seed)).standard_normal() and .random(). All arithmetic that
produces written values (Cholesky, inverses, products, means, covariances) is done in
pure Python floats with math.fsum, so it does not depend on the numpy version or on the
BLAS/LAPACK build. numpy.linalg is used only inside assertions.
"""

