def exact_check(case_id, parsed, pop_sigma, means):
    a = np.array(parsed, dtype=float)
    cov_err = float(np.max(np.abs(np.cov(a, rowvar=False, ddof=1) - np.array(pop_sigma))))
    mean_err = float(np.max(np.abs(a.mean(axis=0) - np.array(means))))
    require(cov_err < 1e-9, f"{case_id}: max |S - Sigma| = {cov_err}")
    require(mean_err < 1e-9, f"{case_id}: max |mean - mu| = {mean_err}")
    return cov_err, mean_err


