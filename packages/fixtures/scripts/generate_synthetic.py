def cid(name):
    return "c_" + name.lower()


def build_model(constructs, paths=(), covariances=(), likert_cols=None, column_override=None):
    likert_cols = likert_cols or {}
    column_override = column_override or {}
    mc, mi, mr = [], [], []
    for c in constructs:
        mc.append({"id": cid(c["name"]), "name": c["name"], "label": c["label"],
                   "measurement": c["measurement"],
                   "indicatorIds": ["i_" + x for x in c["indicators"]]})
        for x in c["indicators"]:
            ind = {"id": "i_" + x, "name": x, "column": column_override.get(x, x)}
            if x in likert_cols:
                ind["scale"] = {"min": likert_cols[x][0], "max": likert_cols[x][1]}
                ind["level"] = "ordinal"
            else:
                ind["level"] = "continuous"
            mi.append(ind)
    for s, t in paths:
        mr.append({"id": f"r_{s.lower()}_{t.lower()}", "kind": "structural", "sourceId": cid(s), "targetId": cid(t)})
    for s, t in covariances:
        mr.append({"id": f"r_{s.lower()}_{t.lower()}", "kind": "covariance", "sourceId": cid(s), "targetId": cid(t)})
    return {"constructs": mc, "indicators": mi, "relationships": mr}


PLS_OPTS = {"innerWeighting": "path", "maxIterations": 300, "tolerance": 1e-7}


def pls(method, engine, *, seed=None, boot=None, ipma=None, missing="listwise"):
    a = {"method": method, "engine": engine, "estimator": "pls-pm", "missingData": missing, "pls": dict(PLS_OPTS)}
    if boot:
        require(seed is not None, "bootstrap requires a seed")
        a["seed"] = seed
        a["bootstrap"] = {"enabled": True, "repetitions": boot, "ci": "percentile",
                          "confidenceLevel": 0.95, "sides": "two-sided"}
    if ipma:
        a["ipma"] = {"targetConstructId": cid(ipma)}
    return a


def cb(engine, estimator="ML", *, ident="marker", means=False, missing="listwise"):
    return {"method": "cb-sem", "engine": engine, "estimator": estimator, "missingData": missing,
            "cb": {"identification": ident, "meanStructure": means}}


def analysis(aid, desc, cfg):
    return {"id": aid, "description": desc, "analysis": cfg}


