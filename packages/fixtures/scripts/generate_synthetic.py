def htmt(cor, a_idx, b_idx):
    het = [cor[i][j] for i in a_idx for j in b_idx]
    ma = [cor[i][j] for i in a_idx for j in a_idx if i < j]
    mb = [cor[i][j] for i in b_idx for j in b_idx if i < j]
    return (math.fsum(het) / len(het)) / math.sqrt((math.fsum(ma) / len(ma)) * (math.fsum(mb) / len(mb)))


