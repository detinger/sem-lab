def rng_for(seed):
    return np.random.Generator(np.random.PCG64(seed))


def draw_sampled(pop, n, seed):
    """Return (standardised rows, raw rows, generator) for N rows of N(mu, Sigma)."""
    rng = rng_for(seed)
    p = len(pop["columns"])
    z = rng.standard_normal((n, p)).tolist()
    lo = cholesky(pop["SigmaStd"])
    std_rows = [[dot(lo[i][: i + 1], zr[: i + 1]) for i in range(p)] for zr in z]
    raw_rows = [[pop["means"][i] + pop["sds"][i] * r[i] for i in range(p)] for r in std_rows]
    return std_rows, raw_rows, rng


def draw_exact(sigma, means, n, seed):
    rng = rng_for(seed)
    p = len(means)
    z = rng.standard_normal((n, p)).tolist()
    zm = column_means(z)
    zc = [[r[j] - zm[j] for j in range(p)] for r in z]
    a = matmul(cholesky(sigma), lower_inverse(cholesky(sample_cov(zc))))
    return [[math.fsum(a[i][k] * r[k] for k in range(p)) + means[i] for i in range(p)] for r in zc]


def likert(x, thresholds, base):
    return base + sum(1 for t in thresholds if x > t)


def likert_profile(name, thresholds, base, smin, smax):
    return {"profile": name, "thresholds": list(thresholds), "lowestCategory": base,
            "highestCategory": base + len(thresholds), "scaleMin": smin, "scaleMax": smax,
            "rule": "category = lowestCategory + number of thresholds strictly exceeded by the standardised continuous response"}


SYM = likert_profile("symmetric-7", SYMMETRIC_7, 1, 1, 7)
HIGH = likert_profile("high-agreement-7", tuple(round(t + HIGH_AGREEMENT_SHIFT, 10) for t in SYMMETRIC_7), 1, 1, 7)
FIVE = likert_profile("symmetric-5", FIVE_POINT, 1, 1, 5)


def shifted_7(name, shift):
    return likert_profile(name, tuple(round(t + shift, 10) for t in SYMMETRIC_7), 1, 1, 7)


LOW = shifted_7("low-agreement-7", 0.4)
MILD = shifted_7("mild-agreement-7", -0.3)

# 10-point items (categories 1..10): nine thresholds 0.5 apart, symmetric around 0; a negative
# shift moves responses towards 10 (the high ratings typical of satisfaction surveys).
TEN_POINT = (-2.0, -1.5, -1.0, -0.5, 0.0, 0.5, 1.0, 1.5, 2.0)


def shifted_10(name, shift):
    return likert_profile(name, tuple(round(t + shift, 10) for t in TEN_POINT), 1, 1, 10)


def discretise(std_rows, columns, profiles):
    out = []
    for r in std_rows:
        out.append([likert(r[j], profiles[c]["thresholds"], profiles[c]["lowestCategory"])
                    for j, c in enumerate(columns)])
    return out


