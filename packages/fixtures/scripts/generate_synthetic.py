# ----------------------------------------------------------------------------------------
# Deterministic linear algebra on lists of Python floats
# ----------------------------------------------------------------------------------------

def dot(a, b) -> float:
    return math.fsum(x * y for x, y in zip(a, b))


def transpose(a):
    return [list(r) for r in zip(*a)]


def matmul(a, b):
    bt = transpose(b)
    return [[dot(r, c) for c in bt] for r in a]


def identity(n):
    return [[1.0 if i == j else 0.0 for j in range(n)] for i in range(n)]


def mat_add(a, b):
    return [[x + y for x, y in zip(ra, rb)] for ra, rb in zip(a, b)]


def mat_sub(a, b):
    return [[x - y for x, y in zip(ra, rb)] for ra, rb in zip(a, b)]


def cholesky(s):
    """Lower Cholesky factor; raises if the matrix is not positive definite."""
    n = len(s)
    lo = [[0.0] * n for _ in range(n)]
    for j in range(n):
        d = s[j][j] - math.fsum(lo[j][k] * lo[j][k] for k in range(j))
        if not d > 0.0:
            raise GenerationError(f"matrix is not positive definite (pivot {j}: {d!r})")
        lo[j][j] = math.sqrt(d)
        for i in range(j + 1, n):
            lo[i][j] = (s[i][j] - math.fsum(lo[i][k] * lo[j][k] for k in range(j))) / lo[j][j]
    return lo


def lower_inverse(lo):
    n = len(lo)
    inv = [[0.0] * n for _ in range(n)]
    for col in range(n):
        for i in range(n):
            rhs = (1.0 if i == col else 0.0) - math.fsum(lo[i][k] * inv[k][col] for k in range(i))
            inv[i][col] = rhs / lo[i][i]
    return inv


def inverse(a):
    """Gauss-Jordan inverse with partial pivoting (small matrices only)."""
    n = len(a)
    m = [list(map(float, r)) + identity(n)[i] for i, r in enumerate(a)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(m[r][c]))
        require(abs(m[p][c]) > 1e-14, "singular matrix in inverse()")
        m[c], m[p] = m[p], m[c]
        piv = m[c][c]
        m[c] = [x / piv for x in m[c]]
        for r in range(n):
            if r != c and m[r][c] != 0.0:
                f = m[r][c]
                m[r] = [x - f * y for x, y in zip(m[r], m[c])]
    return [r[n:] for r in m]


def column_means(rows):
    n = len(rows)
    return [math.fsum(r[j] for r in rows) / n for j in range(len(rows[0]))]


def sample_cov(rows):
    n = len(rows)
    mu = column_means(rows)
    p = len(mu)
    c = [[r[j] - mu[j] for j in range(p)] for r in rows]
    s = [[0.0] * p for _ in range(p)]
    for i in range(p):
        for j in range(i, p):
            v = math.fsum(r[i] * r[j] for r in c) / (n - 1)
            s[i][j] = s[j][i] = v
    return s


def cov_to_cor(s):
    d = [math.sqrt(s[i][i]) for i in range(len(s))]
    return [[s[i][j] / (d[i] * d[j]) for j in range(len(s))] for i in range(len(s))]


