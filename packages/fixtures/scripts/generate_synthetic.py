def reflective(name, label, indicators, loadings):
    require(len(indicators) == len(loadings), f"{name}: loading count")
    return {"name": name, "label": label, "measurement": "reflective",
            "indicators": list(indicators), "loadings": [float(x) for x in loadings]}


def composite(name, label, indicators, r, raw_weights):
    return {"name": name, "label": label, "measurement": "composite-formative",
            "indicators": list(indicators), "R": [[float(x) for x in row] for row in r],
            "rawWeights": [float(x) for x in raw_weights]}


def equicorrelation(k, rho):
    return [[1.0 if i == j else rho for j in range(k)] for i in range(k)]


def build_population(spec):
    """Compute Phi, Sigma (standardised and raw), mu and derived truths from parameters."""
    cons = spec["constructs"]
    names = [c["name"] for c in cons]
    m = len(cons)
    idx = {n: i for i, n in enumerate(names)}

    # Structural matrix B (row = target, column = source); constructs must be listed in
    # a topological order so that B is strictly lower triangular (recursive model).
    b = [[0.0] * m for _ in range(m)]
    for src, tgt, coef in spec.get("paths", []):
        require(idx[src] < idx[tgt], f"construct order is not topological at {src}->{tgt}")
        b[idx[tgt]][idx[src]] = float(coef)
    endogenous = [any(b[i][j] != 0.0 for j in range(m)) for i in range(m)]

    # Psi: exogenous block = specified correlations, unit variances; endogenous
    # disturbance variances chosen so the latent variance is exactly 1.
    psi = [[0.0] * m for _ in range(m)]
    for i in range(m):
        if not endogenous[i]:
            psi[i][i] = 1.0
    for (a, c), r in spec.get("exoCorrelations", {}).items():
        i, j = idx[a], idx[c]
        require(not endogenous[i] and not endogenous[j], f"correlation {a}~{c} must be exogenous")
        psi[i][j] = psi[j][i] = float(r)
    # sequential computation of the covariance among predecessors
    phi_seq = [[0.0] * m for _ in range(m)]
    for i in range(m):
        if not endogenous[i]:
            for j in range(m):
                if not endogenous[j]:
                    phi_seq[i][j] = psi[i][j]
    for i in range(m):
        if endogenous[i]:
            for k in range(i):
                v = math.fsum(b[i][l] * phi_seq[l][k] for l in range(i))
                phi_seq[i][k] = phi_seq[k][i] = v
            explained = math.fsum(b[i][l] * phi_seq[l][k] * b[i][k] for l in range(i) for k in range(i))
            require(explained < 1.0, f"{names[i]}: explained variance {explained} >= 1")
            psi[i][i] = 1.0 - explained
            phi_seq[i][i] = 1.0
    require(all(psi[i][i] > 0 for i in range(m)), "non-positive disturbance variance")
    cholesky(psi)  # Psi must be positive definite

    inv_ib = inverse(mat_sub(identity(m), b))
    phi = matmul(matmul(inv_ib, psi), transpose(inv_ib))
    for i in range(m):
        require(abs(phi[i][i] - 1.0) < 1e-12, f"latent variance of {names[i]} is {phi[i][i]!r}, not 1")
        phi[i][i] = 1.0
        for j in range(m):
            require(abs(phi[i][j] - phi_seq[i][j]) < 1e-12, "Phi formula and sequential Phi disagree")
    phi = [[(phi[i][j] + phi[j][i]) / 2.0 for j in range(m)] for i in range(m)]

    # indicators: loading vector l (lambda for reflective, R w for composite) and the
    # within-block residual covariance (diag(1-lambda^2) or R - (Rw)(Rw)').
    cols, owner, lvec = [], [], []
    blocks = []
    for ci, c in enumerate(cons):
        k = len(c["indicators"])
        if c["measurement"] == "reflective":
            for lam in c["loadings"]:
                require(0.0 < lam < 1.0, f"{c['name']}: standardised loading {lam} outside (0,1)")
            l_c = list(c["loadings"])
            u = [[(1.0 - l_c[i] * l_c[i]) if i == j else 0.0 for j in range(k)] for i in range(k)]
        else:
            r = c["R"]
            w0 = c["rawWeights"]
            scale = math.sqrt(dot(w0, [dot(row, w0) for row in r]))
            w = [x / scale for x in w0]
            c["weights"] = w
            rw = [dot(row, w) for row in r]
            require(abs(dot(w, rw) - 1.0) < 1e-12, f"{c['name']}: w'Rw != 1")
            c["compositeLoadings"] = rw
            l_c = rw
            u = [[r[i][j] - rw[i] * rw[j] for j in range(k)] for i in range(k)]
        blocks.append((len(cols), k, u))
        cols.extend(c["indicators"])
        owner.extend([ci] * k)
        lvec.extend(l_c)
    p = len(cols)
    sig = [[lvec[i] * phi[owner[i]][owner[j]] * lvec[j] for j in range(p)] for i in range(p)]
    for start, k, u in blocks:
        for i in range(k):
            for j in range(k):
                sig[start + i][start + j] += u[i][j]
    for i in range(p):
        require(abs(sig[i][i] - 1.0) < 1e-12, f"standardised variance of {cols[i]} is {sig[i][i]!r}")
        sig[i][i] = 1.0
    cholesky(sig)  # positive definite (raises otherwise)

    sds = [float(spec.get("sds", {}).get(cn, 1.0)) for cn in cols]
    means = [float(spec.get("means", {}).get(cn, 0.0)) for cn in cols]
    sig_raw = [[sds[i] * sig[i][j] * sds[j] for j in range(p)] for i in range(p)]
    return {"spec": spec, "names": names, "B": b, "Psi": psi, "Phi": phi, "invIB": inv_ib,
            "endogenous": endogenous, "columns": cols, "owner": owner, "l": lvec,
            "SigmaStd": sig, "Sigma": sig_raw, "sds": sds, "means": means}


def ols_from_cor(cor, target, preds):
    sub = [[cor[a][b] for b in preds] for a in preds]
    rhs = [cor[a][target] for a in preds]
    inv = inverse(sub)
    return [dot(row, rhs) for row in inv]


def derived_truths(pop):
    names, b, inv_ib, m = pop["names"], pop["B"], pop["invIB"], len(pop["names"])
    effects = []
    for i in range(m):
        for j in range(m):
            total = inv_ib[i][j] - (1.0 if i == j else 0.0)
            if i != j and abs(total) > 1e-15:
                direct = b[i][j]
                effects.append({"source": names[j], "target": names[i], "direct": direct,
                                "indirect": total - direct, "total": total})
    constructs = {}
    q = []
    for c in pop["spec"]["constructs"]:
        if c["measurement"] == "reflective":
            lam = c["loadings"]
            s = math.fsum(lam)
            err = math.fsum(1.0 - x * x for x in lam)
            ll = math.fsum(x * x for x in lam)
            lthl = math.fsum(x * x * (1.0 - x * x) for x in lam)
            rel_mode_a = ll * ll / (ll * ll + lthl)
            q.append(rel_mode_a)
            constructs[c["name"]] = {
                "AVE": ll / len(lam),
                "rhoC": s * s / (s * s + err),
                "rhoA": rel_mode_a,
                "definitions": {
                    "AVE": "mean of squared standardised loadings",
                    "rhoC": "(sum lambda)^2 / ((sum lambda)^2 + sum(1 - lambda^2))",
                    "rhoA": "population rho_A = reliability of the Mode A composite, whose population weights are proportional to lambda: (l'l)^2 / ((l'l)^2 + l'Theta l)",
                },
            }
        else:
            q.append(1.0)
            constructs[c["name"]] = {"weights": c["weights"], "compositeLoadings": c["compositeLoadings"],
                                     "AVE": None, "rhoC": None, "rhoA": None,
                                     "reliabilityApplicability": "not-applicable (composite-formative)"}
    # Classic PLS (no consistency correction) population limit: Mode A weights are
    # proportional to lambda and Mode B weights equal w under any inner scheme, so the
    # composite correlation is Phi_ij * sqrt(q_i q_j) and paths are OLS on those.
    att = [[pop["Phi"][i][j] * (math.sqrt(q[i] * q[j]) if i != j else 1.0) for j in range(m)] for i in range(m)]
    pls_paths = []
    for i in range(m):
        preds = [j for j in range(m) if b[i][j] != 0.0]
        if preds:
            coefs = ols_from_cor(att, i, preds)
            for j, v in zip(preds, coefs):
                pls_paths.append({"source": names[j], "target": names[i], "coefficient": v,
                                  "commonFactorValue": b[i][j]})
    return {"effects": effects, "constructs": constructs,
            "classicPlsPopulationLimit": {
                "description": "Population limit of classic PLS-SEM (Mode A for reflective, Mode B for composite blocks, no consistency correction) on standardised data; independent of the inner weighting scheme.",
                "compositeCorrelations": {"order": names, "matrix": att},
                "paths": pls_paths}}


