def population_json(pop, case_id, *, profiles=None, include_sigma=True, extra=None, note=None):
    spec = pop["spec"]
    truths = derived_truths(pop)
    cons_out = []
    for c in spec["constructs"]:
        d = {"name": c["name"], "label": c["label"], "measurement": c["measurement"], "indicators": c["indicators"]}
        if c["measurement"] == "reflective":
            d["standardizedLoadings"] = dict(zip(c["indicators"], c["loadings"]))
        else:
            d["indicatorCorrelation"] = c["R"]
            d["rawWeights"] = dict(zip(c["indicators"], c["rawWeights"]))
            d["weights"] = dict(zip(c["indicators"], c["weights"]))
            d["compositeLoadings"] = dict(zip(c["indicators"], c["compositeLoadings"]))
            d["weightScaling"] = "weights = rawWeights / sqrt(rawWeights' R rawWeights), so the composite has unit variance"
        cons_out.append(d)
    names = pop["names"]
    inds = []
    for j, col in enumerate(pop["columns"]):
        c = spec["constructs"][pop["owner"][j]]
        d = {"column": col, "construct": c["name"], "mean": pop["means"][j], "sd": pop["sds"][j]}
        if c["measurement"] == "reflective":
            lam = pop["l"][j]
            d["standardizedLoading"] = lam
            d["residualVarianceStandardized"] = 1.0 - lam * lam
            d["residualVarianceRaw"] = (1.0 - lam * lam) * pop["sds"][j] ** 2
        else:
            d["compositeLoading"] = pop["l"][j]
        if profiles and col in profiles:
            d["likert"] = profiles[col]
        inds.append(d)
    out = {
        "caseId": case_id,
        "synthetic": True,
        "constructs": cons_out,
        "structuralCoefficients": [{"source": s, "target": t, "coefficient": float(v)} for s, t, v in spec.get("paths", [])],
        "exogenousCorrelations": [{"a": a, "b": b, "correlation": float(r)} for (a, b), r in spec.get("exoCorrelations", {}).items()],
        "latentDisturbanceVariances": {names[i]: pop["Psi"][i][i] for i in range(len(names)) if pop["endogenous"][i]},
        "latentCorrelation": {"order": names, "matrix": pop["Phi"],
                              "formula": "Phi = (I-B)^-1 Psi (I-B)^-T, every latent variance exactly 1"},
        "indicators": inds,
        "derivedTruths": truths,
        "conventions": {
            "sigma": "Sigma_std = L Phi L' + blockdiag(diag(1-lambda^2) for reflective, R-(Rw)(Rw)' for composite); Sigma_raw = D Sigma_std D, D = diag(sd)",
            "composite": "a composite block's indicators covary with everything outside the block only through the composite: cov(x_block, y) = (R w) cov(C, y)",
        },
    }
    if include_sigma:
        out["impliedCovariance"] = {"columns": pop["columns"], "matrix": pop["Sigma"], "divisor": "population (equals the N-1 sample covariance for EXACT cases)"}
        out["impliedCorrelation"] = {"columns": pop["columns"], "matrix": pop["SigmaStd"]}
    if note:
        out["note"] = note
    if extra:
        out.update(extra)
    return out


